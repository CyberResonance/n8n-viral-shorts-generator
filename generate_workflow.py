"""Builds Viral_Shorts_Generator.json: topic -> Gemini writes a short-form concept (hook, scene prompt, title, caption)
-> optional Gemini Omni 9:16 clip -> poll until ready -> download -> Google Drive -> Discord review message.
Dry run by default: nothing paid is rendered unless the request sets "dryRun": false."""
import json
from pathlib import Path

HERE = Path(__file__).parent
TEXT_MODEL = "gemini-2.5-flash"
VIDEO_MODEL = "gemini-omni-1.1-flash"
API = "https://generativelanguage.googleapis.com/v1beta"

BRIEF_JS = r"""// Normalize the request. dryRun defaults to TRUE: video rendering costs money and must be asked for explicitly.
const b = $input.first().json.body || {};
const clamp = (v, lo, hi, d) => Math.min(hi, Math.max(lo, Number(v) || d));
return [{ json: {
  topic: String(b.topic || '3 automation habits that save a freelancer 5 hours a week').slice(0, 300),
  audience: String(b.audience || 'freelancers and small business owners').slice(0, 200),
  style: String(b.style || 'clean modern motion graphics, bold colors, cinematic lighting').slice(0, 200),
  language: String(b.language || 'English').slice(0, 30),
  seconds: clamp(b.seconds, 4, 10, 8),
  dryRun: b.dryRun === false || b.dryRun === 'false' ? false : true,
} }];"""

SCRIPT_PROMPT_JS = r"""const j = $input.first().json;
const prompt = `You are a short-form video strategist (YouTube Shorts, Instagram Reels).
Create ONE vertical 9:16 short about: ${j.topic}
Audience: ${j.audience}. Visual style: ${j.style}. Language for title, hook and caption: ${j.language}.
The clip is ONE continuous ${j.seconds}-second shot generated by a video model, so the visual must work without cuts.
Rules: hook must create curiosity in the first 2 seconds; no real people, celebrities, logos, brands or copyrighted characters;
safe for work; no medical, financial or legal promises; no text rendered inside the video.
Return JSON only:
{"title": "max 70 chars", "hook": "on-screen hook, max 60 chars", "video_prompt": "detailed visual description of the single shot: subject, motion, camera move, lighting, ambience/music, no dialogue",
 "caption": "max 300 chars, ends with a question or call to action", "hashtags": ["3-5 tags without #"]}`;
return [{ json: { ...j, requestBody: { contents: [{ parts: [{ text: prompt }] }], generationConfig: { temperature: 0.9, responseMimeType: 'application/json' } } } }];"""

PARSE_JS = r"""// Validate the concept and build the video request.
const brief = $('Brief').first().json;
let s = {};
try { s = JSON.parse($input.first().json.candidates?.[0]?.content?.parts?.[0]?.text || '{}'); } catch (e) { s = {}; }
if (!s.video_prompt) throw new Error('Gemini returned no video_prompt: ' + JSON.stringify(s).slice(0, 300));
const tags = (Array.isArray(s.hashtags) ? s.hashtags : []).map(t => '#' + String(t).replace(/[^\p{L}\p{N}_]/gu, '')).filter(t => t.length > 1).slice(0, 5);
const title = String(s.title || brief.topic).slice(0, 70);
const caption = (String(s.caption || '').slice(0, 300) + (tags.length ? '\n\n' + tags.join(' ') : '')).trim();
const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 50) || 'short';
const videoPrompt = `Continuous single shot, vertical 9:16, about ${brief.seconds} seconds, no dialogue, no on-screen text. ${s.video_prompt} Style: ${brief.style}. Safe for work, no real people, no logos.`;
return [{ json: { dryRun: brief.dryRun, topic: brief.topic, title, hook: String(s.hook || '').slice(0, 60), caption, hashtags: tags,
  videoPrompt, fileName: `${slug}.mp4`,
  omniRequest: { model: '__VIDEO_MODEL__', input: videoPrompt, response_format: { type: 'video', aspect_ratio: '9:16', resolution: '720p', delivery: 'uri' }, store: true } } }];""".replace("__VIDEO_MODEL__", VIDEO_MODEL)

VIDEO_JOB_JS = r"""// Find the video file in the Omni response; the poll step checks the file state until it is ACTIVE.
const r = $input.first().json;
const uri = (r.steps || []).flatMap(s => s.content || []).find(c => c.type === 'video')?.uri || '';
const fileId = (uri.split('/files/')[1] || '').split(':')[0].split('?')[0];
if (!fileId) throw new Error('Omni returned no video file: ' + JSON.stringify(r.error || r).slice(0, 400));
return [{ json: { videoUri: uri, fileId } }];"""

REVIEW_JS = r"""// Message for the review channel.
const s = $('Parse Concept').first().json;
const up = $input.first().json;
const link = up.webViewLink || (up.id ? `https://drive.google.com/file/d/${up.id}/view` : '(upload failed)');
const content = [`🎬 **New short ready for review:** ${s.title}`, `**Hook:** ${s.hook}`, `**Caption:**\n${s.caption}`, `**Video:** ${link}`,
  'Review it, then post it yourself or approve it in your publishing queue.'].join('\n\n').slice(0, 1990);
return [{ json: { content, link, title: s.title } }];"""

GEMINI_TEXT = {"method": "POST", "url": f"{API}/models/{TEXT_MODEL}:generateContent",
               "authentication": "predefinedCredentialType", "nodeCredentialType": "googlePalmApi",
               "sendBody": True, "specifyBody": "json", "jsonBody": "={{ JSON.stringify($json.requestBody) }}", "options": {"timeout": 60000}}
GCRED = {"googlePalmApi": {"id": "", "name": "Gemini API"}}
DISCORD = {"authentication": "oAuth2", "resource": "message",
           "guildId": {"__rl": True, "value": "YOUR_DISCORD_SERVER_ID", "mode": "id"},
           "channelId": {"__rl": True, "value": "YOUR_DISCORD_CHANNEL_ID", "mode": "id"}, "options": {}}
BOOL = lambda expr: {"options": {"caseSensitive": True, "typeValidation": "loose", "version": 2}, "combinator": "and",
                     "conditions": [{"leftValue": expr, "rightValue": True, "operator": {"type": "boolean", "operation": "true", "singleValue": True}}]}


def node(name, typ, ver, pos, params, **extra):
    n = {"parameters": params, "name": name, "type": typ, "typeVersion": ver, "position": pos}
    n.update(extra)
    return n


nodes = [
    node("Manual Test (dry run)", "n8n-nodes-base.manualTrigger", 1, [-1300, -100], {}),
    node("Webhook (POST /viral-short)", "n8n-nodes-base.webhook", 2, [-1300, 100],
         {"httpMethod": "POST", "path": "viral-short", "responseMode": "responseNode", "options": {}}, webhookId="viral-short"),
    node("Brief", "n8n-nodes-base.code", 2, [-1080, 0], {"jsCode": BRIEF_JS}),
    node("Build Concept Prompt", "n8n-nodes-base.code", 2, [-860, 0], {"jsCode": SCRIPT_PROMPT_JS}),
    node("Gemini: Concept", "n8n-nodes-base.httpRequest", 4.2, [-640, 0], GEMINI_TEXT, credentials=GCRED,
         retryOnFail=True, maxTries=3, waitBetweenTries=5000),
    node("Parse Concept", "n8n-nodes-base.code", 2, [-420, 0], {"jsCode": PARSE_JS}),
    node("Respond: Concept", "n8n-nodes-base.respondToWebhook", 1.1, [-200, 0],
         {"respondWith": "json", "responseBody": "={{ JSON.stringify({ ok: true, rendering: !$json.dryRun, title: $json.title, hook: $json.hook, caption: $json.caption, videoPrompt: $json.videoPrompt }) }}",
          "options": {}}),
    node("Render Video?", "n8n-nodes-base.if", 2.2, [20, 0], {"conditions": BOOL("={{ $json.dryRun === false }}"), "options": {}}),
    node("Omni: Start Video", "n8n-nodes-base.httpRequest", 4.2, [240, -100], {
        "method": "POST", "url": f"{API}/interactions", "authentication": "predefinedCredentialType", "nodeCredentialType": "googlePalmApi",
        "sendBody": True, "specifyBody": "json", "jsonBody": "={{ JSON.stringify($json.omniRequest) }}", "options": {"timeout": 300000}},
        credentials=GCRED, notes="Paid: roughly $0.10 per second of video."),
    node("Video Job", "n8n-nodes-base.code", 2, [460, -100], {"jsCode": VIDEO_JOB_JS}),
    node("Wait 30s", "n8n-nodes-base.wait", 1.1, [680, -100], {"amount": 30, "unit": "seconds"}, webhookId="viral-short-wait"),
    node("Omni: Poll File", "n8n-nodes-base.httpRequest", 4.2, [900, -100], {
        "method": "GET", "url": f"={{{{ '{API}/files/' + $('Video Job').first().json.fileId }}}}",
        "authentication": "predefinedCredentialType", "nodeCredentialType": "googlePalmApi", "options": {}}, credentials=GCRED),
    node("Video Ready?", "n8n-nodes-base.switch", 3.2, [1120, -100], {"rules": {"values": [
        {"conditions": BOOL("={{ $json.state === 'ACTIVE' }}"), "renameOutput": True, "outputKey": "Ready"},
        {"conditions": BOOL("={{ $json.state === 'PROCESSING' && $runIndex < 30 }}"), "renameOutput": True, "outputKey": "Keep waiting"}]},
        "options": {"fallbackOutput": "extra", "renameFallbackOutput": "Failed"}}),
    node("Download Video", "n8n-nodes-base.httpRequest", 4.2, [1340, -200], {
        "method": "GET", "url": "={{ $('Video Job').first().json.videoUri }}", "authentication": "predefinedCredentialType",
        "nodeCredentialType": "googlePalmApi", "options": {"response": {"response": {"responseFormat": "file", "outputPropertyName": "data"}}, "timeout": 120000}},
        credentials=GCRED),
    node("Upload to Google Drive", "n8n-nodes-base.googleDrive", 3, [1560, -200], {"name": "={{ $('Parse Concept').first().json.fileName }}",
        "driveId": {"__rl": True, "value": "My Drive", "mode": "list", "cachedResultName": "My Drive"},
        "folderId": {"__rl": True, "value": "YOUR_DRIVE_FOLDER_ID", "mode": "id"}, "options": {}},
        credentials={"googleDriveOAuth2Api": {"id": "", "name": "Google Drive"}}),
    node("Build Review Message", "n8n-nodes-base.code", 2, [1780, -200], {"jsCode": REVIEW_JS}),
    node("Discord: Review", "n8n-nodes-base.discord", 2, [2000, -200], {**DISCORD, "content": "={{ $json.content }}"},
         credentials={"discordOAuth2Api": {"id": "", "name": "Discord Bot"}}, retryOnFail=True, maxTries=3, waitBetweenTries=5000),
    node("Video Failed", "n8n-nodes-base.stopAndError", 1, [1340, 40],
         {"errorMessage": "={{ 'Video not ready: ' + JSON.stringify($json.error || $json.state || $json).slice(0, 400) }}"}),
]
C = lambda *t: {"main": [[{"node": x, "type": "main", "index": 0} for x in t]]}
O = lambda *outs: {"main": [[{"node": x, "type": "main", "index": 0}] if x else [] for x in outs]}
conns = {"Manual Test (dry run)": C("Brief"), "Webhook (POST /viral-short)": C("Brief"), "Brief": C("Build Concept Prompt"),
         "Build Concept Prompt": C("Gemini: Concept"), "Gemini: Concept": C("Parse Concept"), "Parse Concept": C("Respond: Concept"),
         "Respond: Concept": C("Render Video?"), "Render Video?": O("Omni: Start Video", None),
         "Omni: Start Video": C("Video Job"), "Video Job": C("Wait 30s"), "Wait 30s": C("Omni: Poll File"), "Omni: Poll File": C("Video Ready?"),
         "Video Ready?": O("Download Video", "Wait 30s", "Video Failed"), "Download Video": C("Upload to Google Drive"),
         "Upload to Google Drive": C("Build Review Message"), "Build Review Message": C("Discord: Review")}
workflow = {"name": "Viral Shorts Generator", "nodes": nodes, "connections": conns, "settings": {"executionOrder": "v1"}}

if __name__ == "__main__":
    out = HERE / "Viral_Shorts_Generator.json"
    out.write_text(json.dumps(workflow, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {out}")
